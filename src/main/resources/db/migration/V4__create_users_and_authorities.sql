CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       login VARCHAR(50) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       first_name VARCHAR(50),
                       last_name VARCHAR(50),
                       email VARCHAR(254) NOT NULL,
                       image_url VARCHAR(256),
                       activated BOOLEAN NOT NULL DEFAULT TRUE,
                       lang_key VARCHAR(10) NOT NULL DEFAULT 'es',
                       created_by VARCHAR(50) NOT NULL DEFAULT 'system',
                       created_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
                       last_modified_by VARCHAR(50),
                       last_modified_date TIMESTAMP WITH TIME ZONE,
                       CONSTRAINT uk_users_login UNIQUE (login),
                       CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE authorities (
                             name VARCHAR(50) PRIMARY KEY
);

CREATE TABLE user_authorities (
                                  user_id BIGINT NOT NULL,
                                  authority_name VARCHAR(50) NOT NULL,
                                  PRIMARY KEY (user_id, authority_name),
                                  CONSTRAINT fk_user_authorities_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
                                  CONSTRAINT fk_user_authorities_authority FOREIGN KEY (authority_name) REFERENCES authorities(name)
);

